/* Split It — service worker v5
   Three strategies, chosen per request:
     • live data (Firestore, exchange rate) → never touched, always network
     • versioned Firebase SDK           → cache-first, it never changes
     • the app shell                    → network-first, cache as the offline fallback
*/
var CACHE = 'splitit-v5';
var SHELL = [
  './',
  './index.html',
  'https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js',
  'https://www.gstatic.com/firebasejs/10.12.2/firebase-firestore-compat.js'
];

self.addEventListener('install', function(e){
  self.skipWaiting();
  e.waitUntil(
    caches.open(CACHE).then(function(c){
      return Promise.all(SHELL.map(function(u){
        return c.add(u).catch(function(){ /* a CDN miss must not fail the install */ });
      }));
    })
  );
});

self.addEventListener('activate', function(e){
  e.waitUntil(
    caches.keys().then(function(keys){
      return Promise.all(keys.map(function(k){ return k === CACHE ? null : caches.delete(k); }));
    }).then(function(){ return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function(e){
  var url = e.request.url;

  // never cache live data
  if (url.indexOf('googleapis.com') !== -1 ||
      url.indexOf('firestore') !== -1 ||
      url.indexOf('open.er-api.com') !== -1) return;

  // versioned SDK — cache first
  if (url.indexOf('gstatic.com') !== -1) {
    e.respondWith(
      caches.match(e.request).then(function(hit){
        return hit || fetch(e.request).then(function(res){
          var copy = res.clone();
          caches.open(CACHE).then(function(c){ c.put(e.request, copy); });
          return res;
        });
      })
    );
    return;
  }

  // app shell — network first, cache as fallback
  e.respondWith(
    fetch(e.request).then(function(res){
      var copy = res.clone();
      caches.open(CACHE).then(function(c){ c.put(e.request, copy).catch(function(){}); });
      return res;
    }).catch(function(){
      return caches.match(e.request).then(function(hit){
        return hit || caches.match('./index.html');
      });
    })
  );
});
